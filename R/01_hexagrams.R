local({
  stopifnot(
    "六十四卦筆數不符"        = nrow(HEXAGRAMS) == 64L,
    "卦序不連續"              = identical(sort(HEXAGRAMS$no), 1:64),
    "有無法辨識的八卦名"      = !anyNA(c(HEXAGRAMS$lower_code, HEXAGRAMS$upper_code)),
    "上下卦組合重複或不完整"  = length(unique(HEXAGRAMS$key)) == 64L
  )
})

#' 依六爻（由下而上的 0/1 向量）查出卦
hex_lookup <- function(lines01) {
  stopifnot(length(lines01) == 6L)
  key <- paste0(trigram_code(lines01[1:3]), "-", trigram_code(lines01[4:6]))
  row <- HEXAGRAMS[HEXAGRAMS$key == key, ]
  if (nrow(row) != 1L) stop("查無此卦：", key)
  list(
    no    = row$no,
    name  = row$name,
    full  = row$full,
    lower = row$lower,
    upper = row$upper,
    tuan  = row$tuan,
    gist  = row$gist,
    lines = lines01
  )
}

#' 爻題：初九、六二、九三、六四、九五、上六
yao_title <- function(pos, is_yang) {
  num <- if (is_yang) "九" else "六"
  if (pos == 1L) return(paste0("初", num))
  if (pos == 6L) return(paste0("上", num))
  paste0(num, c("", "二", "三", "四", "五")[pos])
}
