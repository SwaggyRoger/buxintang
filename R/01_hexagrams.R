.parse_hex <- function(raw) {
  parts <- do.call(rbind, strsplit(raw, "|", fixed = TRUE))
  df <- data.frame(
    no    = as.integer(parts[, 1]),
    name  = parts[, 2],
    lower = parts[, 3],
    upper = parts[, 4],
    full  = parts[, 5],
    tuan  = parts[, 6],
    gist  = parts[, 7],
    stringsAsFactors = FALSE
  )
  df$lower_code <- TRIGRAMS$code[match(df$lower, TRIGRAMS$name)]
  df$upper_code <- TRIGRAMS$code[match(df$upper, TRIGRAMS$name)]
  df$key <- paste0(df$lower_code, "-", df$upper_code)
  df
}

HEXAGRAMS <- .parse_hex(.HEX_RAW)

