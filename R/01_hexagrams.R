# --- 八卦 ------------------------------------------------------------------
TRIGRAMS <- data.frame(
  code   = c(0L, 1L, 2L, 3L, 4L, 5L, 6L, 7L),
  name   = c("坤", "震", "坎", "兌", "艮", "離", "巽", "乾"),
  nature = c("地", "雷", "水", "澤", "山", "火", "風", "天"),
  symbol = c("☷", "☳", "☵", "☱",
             "☶", "☲", "☴", "☰"),
  stringsAsFactors = FALSE
)

trigram_code <- function(lines3) {
  # lines3: 長度 3 的 0/1 向量，由下而上
  as.integer(lines3[1] + 2L * lines3[2] + 4L * lines3[3])
}

trigram_of <- function(code) {
  TRIGRAMS[TRIGRAMS$code == code, ]
}

