.parse_yao <- function(raw) {
  parts <- do.call(rbind, strsplit(raw, "|", fixed = TRUE))
  data.frame(
    no    = as.integer(parts[, 1]),
    name  = parts[, 2],
    title = parts[, 3],
    text  = parts[, 4],
    stringsAsFactors = FALSE
  )
}

YAOCI <- .parse_yao(.YAO_RAW)

